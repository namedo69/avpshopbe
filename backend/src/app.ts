import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import { randomUUID } from 'node:crypto';
import { sqlClient } from './db/sql.js';
import { authRouter, meRouter } from './modules/auth.js';
import { productRouter, adminProductRouter, voucherRouter, adminVoucherRouter } from './modules/catalog.js';
import { depositRouter, webhookRouter, adminDepositRouter } from './modules/deposits.js';
import { orderRouter, adminOrderRouter, walletRouter } from './modules/orders.js';
import { reportRouter } from './modules/reports.js';
import { adminUserRouter } from './modules/users.js';
import { AppError, env } from './lib/core.js';

export const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.frontendOrigin, credentials: true }));
app.use((req, res, next) => {
  req.requestId = randomUUID(); res.setHeader('x-request-id', req.requestId);
  const started = Date.now();
  res.on('finish', () => process.stdout.write(JSON.stringify({ level: 'info', requestId: req.requestId, method: req.method, path: req.originalUrl.split('?')[0], status: res.statusCode, durationMs: Date.now() - started }) + '\n'));
  next();
});
app.get('/health/live', (_req, res) => res.json({ ok: true }));
app.get('/health/ready', async (_req, res) => { await sqlClient.query('SELECT 1 FROM wallets LIMIT 1'); res.json({ ok: true }); });
app.use('/api/v1/webhooks', express.raw({ type: 'application/json', limit: '32kb' }), rateLimit({ windowMs: 60_000, limit: 120 }), webhookRouter);
app.use(express.json({ limit: '64kb' }), cookieParser());
const authLimit = rateLimit({ windowMs: 15 * 60_000, limit: 30 });
app.use('/api/v1/auth', authLimit, authRouter);
app.use('/api/v1', meRouter);
app.use('/api/v1/products', productRouter);
app.use('/api/v1/wallet', walletRouter);
app.use('/api/v1/deposits', rateLimit({ windowMs: 60_000, limit: 20 }), depositRouter);
app.use('/api/v1/vouchers', voucherRouter);
app.use('/api/v1/orders', rateLimit({ windowMs: 60_000, limit: 30 }), orderRouter);
app.use('/api/v1/admin/products', adminProductRouter);
app.use('/api/v1/admin/vouchers', adminVoucherRouter);
app.use('/api/v1/admin/orders', adminOrderRouter);
app.use('/api/v1/admin/deposits', adminDepositRouter);
app.use('/api/v1/admin/reports', reportRouter);
app.use('/api/v1/admin/users', adminUserRouter);
app.use((_req, _res, next) => next(new AppError(404, 'NOT_FOUND', 'Không tìm thấy đường dẫn')));
app.use((error: unknown, req: express.Request, res: express.Response, _next: express.NextFunction) => {
  const known = error instanceof AppError ? error : new AppError(500, 'INTERNAL_ERROR', 'Lỗi máy chủ');
  if (!(error instanceof AppError)) process.stderr.write(JSON.stringify({ level: 'error', requestId: req.requestId, errorType: error instanceof Error ? error.name : 'unknown' }) + '\n');
  res.status(known.status).json({ error: { code: known.code, message: known.message, requestId: req.requestId, fields: known.fields } });
});
